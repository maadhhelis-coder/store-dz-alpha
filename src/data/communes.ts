export function isKnownCommune(wilayaCode: number, name: string): boolean {
  const trimmed = name.trim();
  return communes.some((c) => c.wilayaCode === wilayaCode && c.name === trimmed);
}

export function getCommuneLatinName(wilayaCode: number, arabicName: string): string | null {
  const trimmed = arabicName.trim();
  const found = communes.find((c) => c.wilayaCode === wilayaCode && c.name === trimmed);
  return found?.latin ?? null;
}

